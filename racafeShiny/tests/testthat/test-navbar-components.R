test_that("list items escape text and serialize keys without duplicate DOM IDs", {
  ns <- shiny::NS("parent-child")
  item <- racafeListItem("<script>alert(1)</script>", subtitle = htmltools::HTML("<b>Texto</b>"),
    metadata = c(NIT = "<img src=x>"), value = list(key = "a'\\\"<b>", code = 2), id = "selected", ns = ns)
  html <- as.character(item)
  expect_match(html, "&lt;script&gt;", fixed = TRUE)
  expect_match(html, "&lt;b&gt;Texto&lt;/b&gt;", fixed = TRUE)
  expect_false(grepl("<script>", html, fixed = TRUE))
  expect_identical(item$attribs$`data-rsh-input`, "parent-child-selected")
  expect_null(item$attribs$id)
  expect_identical(jsonlite::fromJSON(item$attribs$`data-rsh-value`)$code, 2L)
  expect_match(as.character(racafeListGroup()), "Sin registros", fixed = TRUE)
  expect_error(racafeListItem("Texto", id = "x"))
  expect_error(racafeListItem("Texto", disabled = NA))
  expect_match(as.character(racafeListItem("Texto", selected = TRUE)), "rsh-list-item--selected", fixed = TRUE)
})

test_that("compact tables preserve the legacy gt style and provide borderless compact output", {
  data <- data.frame(Nombre = "<script>alert(1)</script>", Valor = 1234.56)
  html <- as.character(racafeCompactTable(data, backend = "html", align = c(Valor = "right")))
  expect_match(html, "&lt;script&gt;", fixed = TRUE)
  expect_match(html, "rsh-align-right", fixed = TRUE)
  expect_match(as.character(racafeCompactTable(data.frame(), "html")), "Sin registros", fixed = TRUE)
  expect_error(racafeCompactTable(data, "html", align = "right"))
  expect_error(racafeCompactTable(data, "html", html_columns = "missing"))
  trusted <- as.character(racafeCompactTable(data.frame(x = "<strong>Seguro</strong>"), "html", html_columns = "x"))
  expect_match(trusted, "<strong>Seguro</strong>", fixed = TRUE)
  table <- racafeCompactTable(data, backend = "gt")
  options <- table[["_options"]]
  get <- function(name) options$value[[match(name, options$parameter)]]
  expect_identical(get("table_font_size"), "11px")
  expect_identical(get("table_body_hlines_style"), "none")
  expect_identical(get("table_background_color"), "transparent")
  expect_false(get("row_striping_include_table_body"))
  expect_match(gt::as_raw_html(table), "&lt;script&gt;", fixed = TRUE)
  expect_match(gt::as_raw_html(racafeCompactTable(data.frame(), "gt")), "Sin registros", fixed = TRUE)
  legacy <- gt_minimal_style(gt::gt(data.frame(x = 1)))
  expect_identical(legacy[["_options"]]$value[[match("table_font_size", legacy[["_options"]]$parameter)]], "13px")
})

test_that("overlay IDs and updates use namespaces exactly once", {
  ui <- racafeOverlayLoader("panel", shiny::p("Contenido"), ns = shiny::NS("m"), triggers = "load", visible = TRUE)
  expect_identical(ui$attribs$id, "m-panel")
  expect_match(ui$attribs$`data-rsh-triggers`, "m-load", fixed = TRUE)
  expect_identical(ui$attribs$`aria-busy`, "true")
  expect_identical(racafeOverlayLoader("x")$attribs$`data-rsh-triggers`, "[]")
  expect_error(racafeOverlayLoader("x", size = -1))
  shiny::testServer(function(input, output, session) {
    messages <- list()
    session$sendCustomMessage <- function(type, message) messages[[length(messages) + 1L]] <<- list(type, message)
    racafeUpdateOverlayLoader(session, "panel", TRUE)
    racafeUpdateOverlayLoader(session, session$ns("panel"), FALSE)
    expect_identical(messages[[1]][[2]]$id, session$ns("panel"))
    expect_identical(messages[[2]][[2]]$id, session$ns("panel"))
    expect_false(messages[[2]][[2]]$show)
  }, {})
})
test_that("compact gt scopes header IDs and keeps references coherent after gt transforms", {
  table <- racafeCompactTable(data.frame(Valor = 1), "gt", max_height = "150px")
  table <- gt::cols_align(table, align = "right", columns = tidyselect::all_of("Valor"))
  expect_s3_class(table, "gt_tbl")
  expect_s3_class(table, "rsh_compact_gt")
  tag <- htmltools::as.tags(table)
  html <- as.character(tag)
  expect_match(html, paste0('id="', tag$attribs$id, '-Valor"'), fixed = TRUE)
  expect_match(html, paste0('headers="', tag$attribs$id, '-Valor"'), fixed = TRUE)
  expect_match(tag$attribs$style, "max-height:150px", fixed = TRUE)
})
test_that("scoping GT references never rewrites literal cell text", {
  table <- racafeCompactTable(data.frame(Valor = 'Literal headers="Valor"'), "gt")
  html <- as.character(htmltools::as.tags(table))
  expect_match(html, 'Literal headers="Valor"', fixed = TRUE)
})
