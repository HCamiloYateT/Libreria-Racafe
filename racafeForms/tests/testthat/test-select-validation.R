# Presentación y validación única por formulario ----
test_that("los obligatorios muestran un asterisco sin contaminar la etiqueta de validación", {
  ui <- racafeForm(id = "form", racafeInputText("nombre", "Nombre", required = TRUE))
  html <- as.character(ui)
  expect_match(html, 'class="rf-required"', fixed = TRUE)
  result <- racafeValidateForm(list(nombre = ""), ui)
  expect_identical(result$labels[["nombre"]], "Nombre")
  expect_true(result$required[["nombre"]])
  expect_equal(length(result$errors), 1L)
  expect_false(grepl('class="rf-required"', as.character(racafeInputText("opcional", "Opcional")), fixed = TRUE))
})
test_that("todos los modos heredados muestran solo errores inline sin SweetAlert", {
  result <- racafeValidateForm(list(nombre = ""), racafeInputText("nombre", "Nombre", required = TRUE))
  messages <- list()
  session <- list(sendCustomMessage = function(type, data) messages[[length(messages) + 1L]] <<- list(type, data))
  for (mode in c("inline", "alert", "both")) racafeShowValidation(session, result, mode)
  expect_length(messages, 3L)
  expect_identical(messages[[1]][[2]]$fields, list("nombre"))
  expect_true(all(vapply(messages, function(x) identical(x[[1]], "racafe-validation"), logical(1))))
  expect_true(all(vapply(messages, function(x) isTRUE(x[[2]]$inline), logical(1))))
})
test_that("llamadas repetidas comparten resultado y destroy permite una instancia nueva", {
  shiny::testServer(function(input, output, session) {
    form <- racafeForm(id = "form", racafeInputText("nombre", "Nombre", required = TRUE))
    first <- racafeFormValidation(input, form, session)
    second <- racafeFormValidation(input, form, session, mode = "both")
  }, {
    expect_identical(first, second)
    session$flushReact()
    expect_null(first$result())
    expect_false(first$validate())
    expect_identical(first$result(), second$result())
    session$setInputs(nombre = "Válido")
    expect_true(second$result()$valid)
    first$destroy()
    third <- racafeFormValidation(input, form, session)
    expect_false(identical(first, third))
    expect_false(third$attempted())
  })
})
test_that("las mayúsculas no modifican valores ni etiquetas originales", {
  choices <- c("Café" = "mixCode", "Azúcar" = "sugar")
  before <- choices
  html <- as.character(racafeInputSelect("sel", choices = choices))
  expect_identical(choices, before)
  expect_match(html, "rf-select--uppercase", fixed = TRUE)
  expect_match(html, 'value="mixCode"', fixed = TRUE)
  expect_match(html, "Café", fixed = TRUE)
  plain <- racafeInputSelect("x", choices = choices, uppercase = FALSE)
  expect_false(grepl("rf-select--uppercase", as.character(plain)))
  expect_error(racafeInputSelect("x", choices = choices, uppercase = NA))
  expect_match(as.character(racafeFormRow(racafeInputText("x", "Texto"), racafeButton("b", "Guardar"), actions = TRUE)),
               "rf-row--actions", fixed = TRUE)
  expect_error(racafeFormRow(racafeButton("b", "Guardar"), actions = TRUE))
})
