test_that("detail modal composes existing infrastructure and escapes optional dates", {
  html <- as.character(racafeModalDetail("Detalle", racafeInfoItem("Cliente", "Demo"), metadata = "Sin datos"))
  expect_match(html, "subventana2", fixed = TRUE)
  expect_match(html, "rf-modal-footer", fixed = TRUE)
  expect_match(html, "rf-modal-detail--scroll", fixed = TRUE)
  expect_false(grepl("rf-modal-detail--scroll", as.character(racafeModalDetail("Detalle", scrollable = FALSE))))
  expect_match(as.character(racafeDateLabel("2026-11-04")), "04/11/2026", fixed = TRUE)
  expect_match(as.character(racafeDateLabel("inválido")), "Sin fecha", fixed = TRUE)
  expect_match(as.character(racafeDataBadge("NIT", "<b>1</b>")), "&lt;b&gt;1&lt;/b&gt;", fixed = TRUE)
})
test_that("checklists align states by stable keys instead of display order", {
  ui <- racafeChecklist("activities", c(a = "Revisar", b = "Confirmar"), c(b = TRUE, a = FALSE), ns = shiny::NS("m"))
  html <- as.character(ui)
  expect_match(html, 'id="m-activities"', fixed = TRUE)
  expect_match(html, 'value="b" checked="checked"', fixed = TRUE)
  expect_false(grepl('value="a" checked=', html, fixed = TRUE))
  expect_error(racafeChecklist("x", c(a = "Uno", a = "Dos")))
  expect_error(racafeChecklist("x", c(a = "Uno"), checked = c(other = TRUE)))
  expect_error(racafeChecklist("x", c(a = "Uno"), checked = "missing"))
})
test_that("detail modal does not nest an existing corporate footer", {
  html <- as.character(racafeModalDetail("Detalle", footer = racafeModalFooter(shiny::modalButton("Cerrar"))))
  expect_equal(lengths(regmatches(html, gregexpr('class="rf-modal-footer"', html, fixed = TRUE))), 1)
})
